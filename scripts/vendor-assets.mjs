#!/usr/bin/env node
// Downloads the pinned third-party logos/emoji listed in config/icons.json and
// config/sources.json into assets/icons and assets/emoji, and writes
// assets/icons/SOURCES.md. Run only when the icon list changes; the build
// itself works offline from the vendored copies.
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const icons = readJson('config/icons.json');
const sources = readJson('config/sources.json');

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  const text = await r.text();
  if (!/<svg[\s>]/.test(text)) throw new Error(`not an SVG: ${url}`);
  return text;
};

mkdirSync(join(root, 'assets/icons'), { recursive: true });
mkdirSync(join(root, 'assets/emoji'), { recursive: true });
const rows = [];
for (const [id, spec] of Object.entries(icons)) {
  if (id.startsWith('$')) continue;
  const src = sources[spec.source];
  if (!src) throw new Error(`unknown source ${spec.source} for ${id}`);
  const url = src.base + spec.path;
  writeFileSync(join(root, 'assets/icons', `${id}.svg`), await get(url));
  rows.push(`| ${id} | ${spec.label} | [${spec.source}](${src.home}) | ${src.license} | ${url} |${spec.note ? ' ' + spec.note : ''}`);
  console.log('icon', id);
}
for (const [cp, spec] of Object.entries(sources.emoji)) {
  writeFileSync(join(root, 'assets/emoji', `${cp}.svg`), await get(spec.url));
  rows.push(`| emoji ${cp} | Noto Emoji | [noto-emoji](${spec.home}) | ${spec.license} | ${spec.url} |`);
  console.log('emoji', cp);
}
writeFileSync(join(root, 'assets/icons/SOURCES.md'),
  `# Logo and emoji sources\n\nGenerated by \`npm run vendor\`. Logos are used unmodified except for colour: \`config/icons.json\` may map a\ncolour to the brand's reversed (white) variant for the dark theme, and Simple Icons marks are filled with their\nbrand colour. Logos are trademarks of their owners and are shown only to name the tools I use.\n\n| id | name | set | licence | url | note |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n`);
console.log('done');

// README.md and docs/static.md are generated from profile.config.json so the
// alt texts always match the images. Each image is a <picture>:
//   ≤ 600px wide → compact layout · reduced motion → static file · dark → dark file
// The <img> fallback is the full, light, animated version.
const A = './assets/generated/';

function picture(name, alt, { compact = true, motion = true, base = A } = {}) {
  const src = (variant, theme, stat) => `${base}${name}${variant}-${theme}${stat ? '-static' : ''}.svg`;
  const rows = [];
  const NARROW = '(max-width: 600px)', RM = '(prefers-reduced-motion: reduce)', DARK = '(prefers-color-scheme: dark)';
  const and = (...q) => q.join(' and ');
  if (compact && motion) rows.push([and(NARROW, RM, DARK), src('-compact', 'dark', true)], [and(NARROW, RM), src('-compact', 'light', true)]);
  if (compact) rows.push([and(NARROW, DARK), src('-compact', 'dark')], [NARROW, src('-compact', 'light')]);
  if (motion) rows.push([and(RM, DARK), src('', 'dark', true)], [RM, src('', 'light', true)]);
  rows.push([DARK, src('', 'dark')]);
  return [
    '<picture>',
    ...rows.map(([media, s]) => `  <source media="${media}" srcset="${s}">`),
    `  <img src="${src('', 'light')}" width="100%" alt="${alt.replace(/&/g, '&amp;').replace(/"/g, '&quot;')}">`,
    '</picture>',
  ].join('\n');
}

export function readme(config, iconSpecs) {
  const skillsAlt = config.stack.map((g) => `${g.title}: ${g.rows.flat().map((id) => iconSpecs[id].label).join(', ')}`).join('. ');
  const yearLabels = ['今年', '昨年', '一昨年', '3年前', '4年前'];
  const years = Array.from({ length: config.github.years ?? 3 }, (_, i) => [
    '<details>',
    `<summary>${yearLabels[i] ?? `${i}年前`}</summary>`,
    '',
    picture(`landscape-year${i}`, `3D contribution calendar for ${yearLabels[i] ?? i + ' years ago'} (calendar year)`),
    '',
    '</details>',
  ].join('\n'));
  return `<!--
  Generated by \`npm run build\` from profile.config.json — edit that file, not this one.
  Images live in assets/generated/ and are refreshed daily by .github/workflows/update-profile.yml.
-->

${picture('hero', config.intro.alt)}

${picture('section-skills', config.sections.skills, { motion: false })}

${picture('skills', skillsAlt)}

${picture('section-activity', config.sections.activity, { motion: false })}

${picture('landscape', '3D contribution calendar of the last 12 months: one block per day, block height by number of contributions')}

${years.join('\n\n')}

${picture('charts', 'Donut: commits of the past year by repository primary language. Radar (log scale): commits, issues, pull requests, reviews and new repositories in the past year.')}

<sub>アニメーションなしの画像は <a href="./docs/static.md">静止画版</a> で見られます。</sub>
`;
}

export function staticPage(config) {
  const items = [
    ['hero', config.intro.alt], ['skills', 'Tech stack'], ['landscape', 'Contributions, last 12 months'],
    ...Array.from({ length: config.github.years ?? 3 }, (_, i) => [`landscape-year${i}`, `Contributions, calendar year (${i})`]),
    ['charts', 'Languages and activity'],
  ];
  return `# 静止画版 / Static images\n\nThe profile images without animation (generated).\n\n${items.map(([n, alt]) => [
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="../assets/generated/${n}-dark-static.svg">`,
    `  <img src="../assets/generated/${n}-light-static.svg" width="100%" alt="${alt}">`,
    '</picture>',
  ].join('\n')).join('\n\n')}\n\n[← Back to the profile](../README.md)\n`;
}
